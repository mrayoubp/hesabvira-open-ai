export async function ensureChartOfAccounts(
  ctx: MutationCtx,
  businessId: Id<"businesses">,
  actorId: Id<"users">,
) {
  const existing = await ctx.db
    .query("accounts")
    .withIndex("by_business", (q) => q.eq("businessId", businessId))
    .take(2000);
  if (existing.length >= 2000) return { created: 0 };

  const now = Date.now();
  const ids = new Map<string, Id<"accounts">>(
    existing.map((account) => [account.code, account._id]),
  );
  let created = 0;

  for (const account of DEFAULT_CHART) {
    if (ids.has(account.code)) continue;
    const parentId = account.parentCode
      ? ids.get(account.parentCode)
      : undefined;
    if (account.parentCode && !parentId) {
      throw new Error(
        `حساب والد ${account.parentCode} برای حساب پیش‌فرض ${account.code} پیدا نشد.`,
      );
    }
    const accountId = await ctx.db.insert("accounts", {
      businessId,
      code: account.code,
      name: account.name,
      level: account.level,
      type: account.type,
      nature: account.nature,
      parentId,
      postable: Boolean(account.postable),
      detailKind: account.detailKind ?? "none",
      systemKey: account.systemKey,
      description: account.description,
      createdBy: actorId,
      createdAt: now,
      updatedAt: now,
      active: true,
    });
    ids.set(account.code, accountId);
    created += 1;
  }

  return { created };
}

export async function getSystemAccount(
  ctx: MutationCtx,
  businessId: Id<"businesses">,
  systemKey: string,
) {
  return await ctx.db
    .query("accounts")
    .withIndex("by_business_system", (q) =>
      q.eq("businessId", businessId).eq("systemKey", systemKey),
    )
    .unique();
}

/** Active detail accounts, the only accounts allowed on a new document line. */
export async function postableAccounts(
  ctx: MutationCtx,
  businessId: Id<"businesses">,
) {
  return await ctx.db
    .query("accounts")
    .withIndex("by_business_active", (q) =>
      q.eq("businessId", businessId).eq("active", true),
    )
    .filter((q) => q.eq(q.field("level"), "detail"))
    .collect();
}
